#!/usr/bin/env python3
"""Generates a compact Typst table of the HBC v96 opcodes (the appendix of the thesis).

Reads core/src/format/opcodes_v96.cpp (itself generated by seeder/gen_opcodes.py)
and writes a Typst fragment with: opcode, mnemonic, typed operands and total
instruction size in bytes.

Usage, from the repository root:
    .venv/bin/python tools/gen_opcode_table_typ.py <output.typ>
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "core/src/format/opcodes_v96.cpp"

# tipo fisico (nome esatto del sorgente) -> byte
TYPES = {
    "Reg8": 1, "Reg32": 4, "UInt8": 1, "UInt16": 2, "UInt32": 4,
    "Imm32": 4, "Double": 8, "Addr8": 1, "Addr32": 4,
}

ROW = re.compile(
    r'/\*\s*0x([0-9A-F]{2})\s*\*/\s*\{\s*"(\w+)",\s*(\d+),\s*\{([^}]*)\},\s*0x([0-9A-Fa-f]+)'
)


def parse(text):
    rows = []
    for m in ROW.finditer(text):
        op, name, n, ops, mask = m.groups()
        types = re.findall(r"OperandType::(\w+)", ops)
        assert len(types) == int(n), (name, types, n)
        mask = int(mask, 16)
        cols, size = [], 1  # 1 byte di opcode
        for i, t in enumerate(types):
            nb = TYPES[t]
            sig = t + ("*" if mask >> i & 1 else "")  # * = indice in String Table
            cols.append(sig)
            size += nb
        rows.append((op, name, cols, size))
    return rows


def main():
    out = Path(sys.argv[1])
    rows = parse(SRC.read_text())
    lines = [
        "// GENERATO da hermit/tools/gen_opcode_table_typ.py a partire da",
        "// core/src/format/opcodes_v96.cpp. NON modificare a mano.",
        f"// {len(rows)} opcode definiti su 256.",
        "#pagebreak(weak: true)",
        "#set text(size: 9.5pt)",
        "#table(",
        "  columns: (auto, auto, 1fr, auto),",
        "  align: (center, left, left, center),",
        "  inset: (x: 4pt, y: 2.5pt),",
        "  table.header(repeat: true, [*Op*], [*Mnemonic*], [*Operandi*], [*B*]),",
    ]
    for op, name, cols, size in rows:
        ops = ", ".join(cols) if cols else "—"
        lines.append(f"  [`{op}`], [`{name}`], [`{ops}`], [{size}],")
    lines += [")"]
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} opcode -> {out}")


if __name__ == "__main__":
    main()
