#!/usr/bin/env python3
"""
gen_long_literal_sample.py - generates array_object_literals_long.js.

NewArrayWithBufferLong/NewObjectWithBufferLong are NOT selected because a
literal has many elements: `count`/`sizeHint` stay UInt16 in both variants
(core/src/format/opcodes_v96.cpp) - only the buffer-offset operand widens,
from UInt16 to UInt32. The array buffer / object value buffer are file-wide
(one blob shared by every literal in the compilation unit), so the Long
variant only triggers when an EARLIER literal has already pushed that
buffer past 65535 bytes.

This generates one big array (bigArr) and one big object (bigObj) - each
with just enough int32 elements (4 bytes/element) to cross that threshold
- followed by a small arrLong/objLong whose own buffer offset then no
longer fits UInt16. Verified against `hermes -dump-bytecode`.

Usage:
    .venv/bin/python seeder/gen_long_literal_sample.py
    .venv/bin/python -m seeder.compile seeder/samples/array_object_literals_long.js
"""

from pathlib import Path

SAMPLES_DIR = Path(__file__).parent / "samples"

# int32 elements are 4 bytes each in the array buffer / object value buffer;
# 16400 * 4 = 65600 > 65535 (UInt16 range), with margin for RLE run headers.
N = 16400


def generate() -> str:
    big_arr = ", ".join(str(i) for i in range(N))
    big_obj = ", ".join(f"k{i}: {i}" for i in range(N))
    return (
        '"use strict";\n'
        "// Generated by seeder/gen_long_literal_sample.py - do not hand-edit.\n"
        "//\n"
        "// NewArrayWithBufferLong/NewObjectWithBufferLong oracle:\n"
        f"// the {N}-element `bigArr`/`bigObj` push the array buffer / object value\n"
        "// buffer past the 65535-byte UInt16 offset range, so `arrLong`/`objLong`\n"
        "// (declared right after) get emitted with the Long variant - confirmed with\n"
        "// `hermes -dump-bytecode`:\n"
        "//   NewArrayWithBufferLong r1, 3, 3, 65610\n"
        "//   NewObjectWithBufferLong r1, 2, 2, 32560, 65610\n"
        f"var bigArr = [{big_arr}];\n"
        "var arrLong = [7, 8, 9];\n"
        f"var bigObj = {{{big_obj}}};\n"
        "var objLong = {x: 1, y: 2};\n"
        "print(bigArr.length, arrLong[0], bigObj.k0, objLong.x);\n"
    )


def main() -> None:
    SAMPLES_DIR.mkdir(exist_ok=True)
    path = SAMPLES_DIR / "array_object_literals_long.js"
    src = generate()
    path.write_text(src)
    print(f"generated {path} ({len(src)} bytes, N={N})")


if __name__ == "__main__":
    main()
