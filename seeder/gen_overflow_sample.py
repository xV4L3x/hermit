#!/usr/bin/env python3
"""
gen_overflow_sample.py - generates and compiles overflow_func.ts.

Produces a function with environmentSize > 255 (260 variables captured
by nested closures) and a try/catch, replicating the characteristics of
function 395 in ridemovi.hbc (overflowed SmallFuncHeader + hasExceptionHandler).

Goal: have a .hbc file whose structure we know, to figure out where
Hermes puts the real infoOffset for overflow functions.

Usage:
    cd hermit/
    python seeder/gen_overflow_sample.py [--hermes PATH] [--nvars N]
"""

import argparse
import subprocess
import sys
from pathlib import Path

SAMPLES_DIR = Path(__file__).parent / "samples"
CORPUS_DIR  = Path(__file__).parent / "corpus"

def generate_ts(n: int) -> str:
    lines = [
        "// overflow_func.ts - function that triggers a SmallFuncHeader overflow",
        "// Generated by seeder/gen_overflow_sample.py",
        "//",
        f"// environmentSize = {n} > 255  ->  overflowed = 1",
        "// hasExceptionHandler = true  (try/catch/throw)",
        "",
        "// prettier-ignore",
        "function makeOverflow(",
        "    p1: any, p2: any, p3: any, p4: any, p5: any, p6: any, p7: any",
        "): any[] {",
        "",
        f"    // {n} local variables captured by the closures -> environmentSize = {n}",
    ]

    # Dichiara N variabili (8 per riga per compattezza)
    for i in range(0, n, 8):
        chunk = range(i, min(i + 8, n))
        decls = "  ".join(f"let v{j:03d} = p1 + {j};" for j in chunk)
        lines.append(f"    {decls}")

    lines.append("")
    lines.append(f"    // {n} closures that capture the variables")

    for i in range(0, n, 4):
        chunk = range(i, min(i + 4, n))
        decls = "  ".join(f"const c{j:03d} = () => v{j:03d};" for j in chunk)
        lines.append(f"    {decls}")

    lines.append("")
    lines.append("    // try/catch/throw - sets hasExceptionHandler = true")
    lines.append("    try {")
    lines.append("        if (typeof c000() !== 'number') throw new Error('type mismatch');")
    lines.append("        if (typeof c001() !== 'number') throw new Error('type mismatch');")
    lines.append("    } catch (e: any) {")
    lines.append("        console.log('caught:', e.message);")
    lines.append("        throw e;")
    lines.append("    }")
    lines.append("")

    # Return an array of all the closures (keeps them alive -> they don't get optimized away)
    lines.append("    return [")
    for i in range(0, n, 8):
        chunk = range(i, min(i + 8, n))
        items = ", ".join(f"c{j:03d}" for j in chunk)
        sep = "," if min(i + 8, n) < n else ""
        lines.append(f"        {items}{sep}")
    lines.append("    ];")
    lines.append("}")
    lines.append("")
    lines.append("const fns = makeOverflow(1, 2, 3, 4, 5, 6, 7);")
    lines.append("console.log('closures:', fns.length);")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hermes", default="hermes", help="Path to hermes binary")
    parser.add_argument("--nvars", type=int, default=260,
                        help="Number of captured variables (must be > 255 to overflow)")
    args = parser.parse_args()

    if args.nvars <= 255:
        print(f"WARNING: nvars={args.nvars} <= 255, SmallFuncHeader will NOT overflow")

    SAMPLES_DIR.mkdir(exist_ok=True)
    CORPUS_DIR.mkdir(exist_ok=True)

    ts_path  = SAMPLES_DIR / "overflow_func.ts"
    hbc_path = CORPUS_DIR  / "overflow_func.hbc"

    ts_src = generate_ts(args.nvars)
    ts_path.write_text(ts_src)
    print(f"TS generated: {ts_path}  ({len(ts_src)} bytes, {args.nvars} variables)")

    # Compile directly with hermes (no need for tsc - hermes accepts JS/TS-like)
    # Note: hermes does not support TypeScript natively; compile with tsc first or
    # strip the type annotations. We use --allow-hermes-es6 for arrow functions.
    # If hermes fails on TS, try tsc --target ES6 first.
    r = subprocess.run(
        [args.hermes, "-emit-binary", "-out", str(hbc_path), str(ts_path)],
        capture_output=True, text=True,
    )

    if r.returncode != 0:
        print(f"hermes failed directly on .ts, trying tsc...")
        # Fallback: compile .ts -> .js with tsc, then hermes on the .js
        import tempfile
        with tempfile.NamedTemporaryFile(suffix=".js", mode="w", delete=False) as f:
            tmp_js = Path(f.name)

        # Manually strip the TypeScript type annotations (simple approach)
        js_src = ts_src
        js_src = js_src.replace(": any", "").replace(": any[]", "")
        tmp_js.write_text(js_src)

        r2 = subprocess.run(
            [args.hermes, "-emit-binary", "-out", str(hbc_path), str(tmp_js)],
            capture_output=True, text=True,
        )
        tmp_js.unlink(missing_ok=True)

        if r2.returncode != 0:
            print(f"hermes also failed on the stripped JS:\n{r2.stderr.strip()}")
            print(f"\nTry manually:")
            print(f"  tsc --target ES6 --outFile /tmp/overflow_func.js {ts_path}")
            print(f"  hermes -emit-binary -out {hbc_path} /tmp/overflow_func.js")
            sys.exit(1)
    else:
        print(f"Compiled with hermes: {hbc_path}  ({hbc_path.stat().st_size} bytes)")
        return

    print(f"Compiled (via JS strip): {hbc_path}  ({hbc_path.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
